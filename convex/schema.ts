import { defineSchema, defineTable } from "convex/server";
import { authTables } from "@convex-dev/auth/server";
import { v } from "convex/values";
import {
  humanRole,
  mode,
  invoiceInput,
  state,
  result,
  role,
  line,
} from "./validators";
export default defineSchema({
  ...authTables,
  profiles: defineTable({
    identity: v.string(),
    role: humanRole,
    sandboxId: v.id("sandboxes"),
  }).index("by_identity", ["identity"]),
  sandboxes: defineTable({
    owner: v.string(),
    generation: v.number(),
    mode,
    archived: v.boolean(),
    createdAt: v.number(),
  }),
  cases: defineTable({
    sandboxId: v.id("sandboxes"),
    input: invoiceInput,
    revision: v.number(),
    state,
    phase: v.string(),
    mode,
    updatedAt: v.number(),
    attempt: v.number(),
    proposalId: v.optional(v.id("proposals")),
    policyId: v.optional(v.id("policies")),
    workflowId: v.optional(v.string()),
    runId: v.optional(v.string()),
    providerStatus: v.optional(v.string()),
    error: v.optional(v.string()),
    resolution: v.optional(
      v.object({
        sourceId: v.string(),
        amountCents: v.number(),
        text: v.string(),
        actor: v.string(),
      }),
    ),
  })
    .index("by_sandboxId", ["sandboxId"])
    .index("by_sandboxId_and_code", ["sandboxId", "input.code"]),
  proposals: defineTable({
    caseId: v.id("cases"),
    sandboxId: v.id("sandboxes"),
    revision: v.number(),
    attempt: v.number(),
    createdAt: v.number(),
    proposedBy: v.string(),
    result,
    input: invoiceInput,
    policyId: v.optional(v.id("policies")),
    mode,
    runId: v.optional(v.string()),
  }).index("by_caseId", ["caseId"]),
  approvals: defineTable({
    caseId: v.id("cases"),
    proposalId: v.id("proposals"),
    action: v.string(),
    decision: v.string(),
    actor: v.string(),
    role: humanRole,
    reason: v.string(),
    createdAt: v.number(),
    revision: v.number(),
  }).index("by_caseId", ["caseId"]),
  questions: defineTable({
    caseId: v.id("cases"),
    text: v.string(),
    createdAt: v.number(),
    answer: v.optional(v.string()),
    answeredBy: v.optional(v.string()),
    answeredAt: v.optional(v.number()),
  }).index("by_caseId", ["caseId"]),
  journals: defineTable({
    caseId: v.id("cases"),
    sandboxId: v.id("sandboxes"),
    reference: v.string(),
    proposalId: v.id("proposals"),
    approvalId: v.id("approvals"),
    lines: v.array(line),
    period: v.string(),
    createdAt: v.number(),
    reversalOf: v.optional(v.id("journals")),
    reason: v.string(),
  })
    .index("by_caseId", ["caseId"])
    .index("by_reference", ["reference"])
    .index("by_sandboxId", ["sandboxId"]),
  audit: defineTable({
    sandboxId: v.id("sandboxes"),
    caseId: v.optional(v.id("cases")),
    timestamp: v.number(),
    actor: v.string(),
    role,
    action: v.string(),
    allowed: v.boolean(),
    before: v.string(),
    after: v.string(),
    reason: v.string(),
    evidenceIds: v.array(v.string()),
    policyId: v.optional(v.id("policies")),
    proposalId: v.optional(v.id("proposals")),
    approvalId: v.optional(v.id("approvals")),
    postingRef: v.optional(v.string()),
  })
    .index("by_sandboxId", ["sandboxId"])
    .index("by_caseId", ["caseId"]),
  precedents: defineTable({
    sandboxId: v.id("sandboxes"),
    code: v.string(),
    vendor: v.string(),
    date: v.string(),
    title: v.string(),
    explanation: v.string(),
    active: v.boolean(),
  }).index("by_sandboxId", ["sandboxId"]),
  policies: defineTable({
    sandboxId: v.id("sandboxes"),
    version: v.number(),
    title: v.string(),
    vendor: v.string(),
    status: v.union(
      v.literal("candidate"),
      v.literal("active"),
      v.literal("superseded"),
    ),
    procedure: v.union(
      v.literal("controller_confirmation"),
      v.literal("signed_schedule_first"),
    ),
    description: v.string(),
    precedentIds: v.array(v.string()),
    createdAt: v.number(),
    approvedBy: v.optional(v.string()),
    approvedAt: v.optional(v.number()),
    checks: v.array(v.object({ name: v.string(), passed: v.boolean() })),
    origin: v.string(),
  }).index("by_sandboxId", ["sandboxId"]),
  policyRuns: defineTable({
    sandboxId: v.id("sandboxes"),
    mode,
    procedure: v.union(
      v.literal("controller_confirmation"),
      v.literal("signed_schedule_first"),
    ),
    status: v.string(),
    createdAt: v.number(),
    runId: v.optional(v.string()),
    error: v.optional(v.string()),
    policyId: v.optional(v.id("policies")),
    caseId: v.optional(v.id("cases")),
  }).index("by_sandboxId", ["sandboxId"]),
  periods: defineTable({
    sandboxId: v.id("sandboxes"),
    month: v.string(),
    closed: v.boolean(),
  }).index("by_sandboxId_and_month", ["sandboxId", "month"]),
  runs: defineTable({
    caseId: v.id("cases"),
    attempt: v.number(),
    externalId: v.optional(v.string()),
    status: v.string(),
    raw: v.optional(v.string()),
    createdAt: v.number(),
    completedAt: v.optional(v.number()),
  }).index("by_caseId", ["caseId"]),
});
